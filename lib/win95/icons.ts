export function icon(name: IconName, size: 16 | 32 = 32): string {
  // Allow fully-qualified paths/URLs for custom (portfolio) logos.
  if (name.startsWith("/") || name.startsWith("http") || name.startsWith("data:")) return name
  return size === 16 ? `/icons/${name}-16.png` : `/icons/${name}.png`
}
